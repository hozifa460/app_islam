  // ✅ Maps للوصول السريع O(1)
  // ══════════════════════════════════════════════════════

  static final Map<int, IslamicRadioStation> _byIdMap = {
    for (final s in all) s.id: s,
  };

  static final Map<String, List<IslamicRadioStation>> _byCategoryMap = () {
    final map = <String, List<IslamicRadioStation>>{};
    for (final s in all) {
      map.putIfAbsent(s.category, () => []).add(s);
    }
    return map;
  }();

  // ✅ Categories مرتبة كما وردت
  static final List<String> _categoriesList = () {
    final seen = <String>{};
    final result = <String>[];
    for (final s in all) {
      if (seen.add(s.category)) result.add(s.category);
    }
    return result;
  }();

  // ✅ القراء الذين يدعمون التحميل - محسوبون مرة واحدة
  static final List<IslamicRadioStation> reciters =
  all.where((s) => s.supportsDownload).toList();

  // ══ دوال الوصول ══

  /// البحث بالـ ID - O(1)
  static IslamicRadioStation? byId(int id) => _byIdMap[id];

  /// البحث بالتصنيف - O(1)
  static List<IslamicRadioStation> byCategory(String category) =>
      _byCategoryMap[category] ?? [];

  /// قائمة التصنيفات - O(1)
  static List<String> get categories => _categoriesList;

  /// البحث النصي - O(n) لكن مع مقارنة أسرع
  static List<IslamicRadioStation> search(String query) {
    if (query.isEmpty) return all;
    final q = query.toLowerCase();
    return all.where((s) {
      return s.name.contains(query) ||
          s.nameEn.toLowerCase().contains(q) ||
          s.category.contains(query) ||
          s.description.contains(query);
    }).toList();
  }
