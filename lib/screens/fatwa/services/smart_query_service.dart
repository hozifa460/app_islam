class SmartQueryService {

  // ══════════════════════════════════════
  // توليد عدة صياغات للبحث من سؤال واحد
  // ══════════════════════════════════════
  static List<String> generateSearchQueries(String userQuestion) {
    final queries = <String>[];

    // 1. السؤال الأصلي
    queries.add(userQuestion);

    // 2. السؤال بعد تنظيف العامية
    final formal = _convertToFormal(userQuestion);
    if (formal != userQuestion) {
      queries.add(formal);
    }

    // 3. استخراج الموضوع الأساسي
    final topic = _extractTopic(userQuestion);
    if (topic.isNotEmpty && topic != userQuestion) {
      queries.add(topic);
    }

    // 4. إعادة صياغة كسؤال فقهي
    final fiqhQuery = _reformulateAsFiqh(userQuestion);
    if (fiqhQuery.isNotEmpty) {
      queries.add(fiqhQuery);
    }

    // 5. توسيع بالمرادفات
    final expanded = _expandWithSynonyms(userQuestion);
    if (expanded != userQuestion) {
      queries.add(expanded);
    }

    // إزالة المكرر
    final unique = queries.toSet().toList();

    print('🧠 صياغات البحث المولّدة:');
    for (var i = 0; i < unique.length; i++) {
      print('   ${i + 1}. ${unique[i]}');
    }

    return unique;
  }

  // ══════════════════════════════════════
  // تحويل العامية إلى فصحى
  // ══════════════════════════════════════
  static String _convertToFormal(String text) {
    final dialectMap = {
      // عامية خليجية
      'وش': 'ما',
      'ايش': 'ما',
      'ليش': 'لماذا',
      'اللي': 'الذي',
      'يقدر': 'يستطيع',
      'تقدر': 'تستطيع',
      'لازم': 'يجب',
      'مو': 'ليس',
      'ابي': 'أريد',
      'ابغى': 'أريد',
      'يبي': 'يريد',
      'وين': 'أين',
      'كذا': 'هكذا',
      'حق': 'خاص بـ',
      'شلون': 'كيف',
      'هالشي': 'هذا الشيء',

      // عامية مصرية
      'عايز': 'أريد',
      'مش': 'ليس',
      'ازاي': 'كيف',
      'ليه': 'لماذا',
      'فين': 'أين',
      'كده': 'هكذا',
      'دي': 'هذه',
      'ده': 'هذا',
      'بتاع': 'خاص بـ',

      // تحويلات شائعة
      'بالصلاة': 'في الصلاة',
      'بالصيام': 'في الصيام',
      'بالحج': 'في الحج',
      'بالوضوء': 'في الوضوء',
      'بالزكاة': 'في الزكاة',
      'ما يجوز': 'لا يجوز',
      'ما يصح': 'لا يصح',
      'لو': 'إذا',
      'وانا': 'وأنا',
    };

    String result = text;
    for (final entry in dialectMap.entries) {
      result = result.replaceAll(
        RegExp('\\b${entry.key}\\b'), entry.value,
      );
    }

    return result;
  }

  // ══════════════════════════════════════
  // استخراج الموضوع الأساسي
  // ══════════════════════════════════════
  static String _extractTopic(String question) {
    // إزالة كلمات السؤال العامة
    const questionWords = [
      'هل', 'ما', 'ما هو', 'ما هي', 'ما حكم', 'ما معنى',
      'كيف', 'متى', 'لماذا', 'أين', 'هل يجوز', 'هل يصح',
      'هل يمكن', 'هل يجب', 'ما رأي', 'ما قول',
      'أريد أن أعرف', 'أريد أسأل', 'سؤالي هو',
      'لو سمحت', 'من فضلك', 'جزاكم الله خيرا',
      'بارك الله فيكم', 'أفيدونا', 'أفتونا',
      'يا شيخ', 'يا فضيلة الشيخ',
    ];

    String topic = question;
    for (final word in questionWords) {
      topic = topic.replaceAll(word, '');
    }

    return topic.replaceAll(RegExp(r'\s+'), ' ').trim();
  }

  // ══════════════════════════════════════
  // إعادة صياغة كسؤال فقهي
  // ══════════════════════════════════════
  static String _reformulateAsFiqh(String question) {
    final q = question.toLowerCase();
    final topic = _extractTopic(question);

    if (topic.isEmpty) return '';

    // إذا السؤال عن حكم
    if (q.contains('يجوز') || q.contains('حكم') || q.contains('حلال') || q.contains('حرام')) {
      return 'حكم $topic';
    }

    // إذا السؤال عن كيفية
    if (q.contains('كيف') || q.contains('طريقة')) {
      return 'كيفية $topic';
    }

    // إذا السؤال عن وقت
    if (q.contains('متى') || q.contains('وقت')) {
      return 'وقت $topic';
    }

    // إذا السؤال عن شروط
    if (q.contains('شروط') || q.contains('شرط')) {
      return 'شروط $topic';
    }

    return 'حكم $topic';
  }

  // ══════════════════════════════════════
  // توسيع بالمرادفات
  // ══════════════════════════════════════
