        q.contains('حكم') ||
        q.contains('حلال') ||
        q.contains('حرام')) {
      return 'حكم $topic';
    }

    // ط¥ط°ط§ ط§ظ„ط³ط¤ط§ظ„ ط¹ظ† ظƒظٹظپظٹط©
    if (q.contains('كيف') || q.contains('طريقة')) {
      return 'كيفية $topic';
    }

    // ط¥ط°ط§ ط§ظ„ط³ط¤ط§ظ„ ط¹ظ† ظˆظ‚طھ
    if (q.contains('متى') || q.contains('وقت')) {
      return 'وقت $topic';
    }

    // ط¥ط°ط§ ط§ظ„ط³ط¤ط§ظ„ ط¹ظ† ط´ط±ظˆط·
    if (q.contains('شروط') || q.contains('شرط')) {
      return 'شروط $topic';
    }

    return 'حكم $topic';
  }

