  static String _reformulateAsFiqh(String question) {
    final q = question.toLowerCase();
    final topic = _extractTopic(question);

    if (topic.isEmpty) return '';

    // ط¥ط°ط§ ط§ظ„ط³ط¤ط§ظ„ ط¹ظ† ط­ظƒظ…
