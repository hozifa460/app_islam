      'صيام': ['صيام', 'صوم', 'الصيام', 'يصوم', 'صائم', 'أصوم'],
      'زكاة': ['زكاة', 'الزكاة', 'صدقة', 'زكاة المال'],
      'حج': ['حج', 'الحج', 'عمرة', 'العمرة', 'حاج', 'معتمر'],
      'وضوء': ['وضوء', 'الوضوء', 'يتوضأ', 'توضأ', 'طهارة'],

      // أفعال
      'عطس': ['عطس', 'عطاس', 'العطاس', 'عطست', 'يعطس', 'العاطس'],
      'أكل': ['أكل', 'يأكل', 'طعام', 'أكلت', 'الأكل', 'تناول'],
      'شرب': ['شرب', 'يشرب', 'شربت', 'الشرب', 'شراب'],
      'نام': ['نام', 'نوم', 'ينام', 'نمت', 'النوم', 'نائم'],
      'جلس': ['جلس', 'جالس', 'قاعد', 'جلوس', 'يجلس'],
      'قام': ['قام', 'قائم', 'وقف', 'يقوم', 'القيام'],
      'سجد': ['سجد', 'سجود', 'يسجد', 'ساجد', 'السجود'],
      'ركع': ['ركع', 'ركوع', 'يركع', 'راكع', 'الركوع'],

      // أحكام
      'حلال': ['حلال', 'جائز', 'يجوز', 'مباح', 'يباح'],
      'حرام': ['حرام', 'محرم', 'لا يجوز', 'ممنوع', 'يحرم'],
      'واجب': ['واجب', 'فرض', 'يجب', 'لازم', 'وجوب'],
      'سنة': ['سنة', 'مستحب', 'يستحب', 'مندوب', 'نافلة'],
      'مكروه': ['مكروه', 'يكره', 'كراهة'],

      // أشخاص
      'مريض': ['مريض', 'مرض', 'المريض', 'عليل', 'سقيم', 'مرضت'],
      'مسافر': ['مسافر', 'سفر', 'السفر', 'يسافر', 'رحلة'],
      'حامل': ['حامل', 'حمل', 'الحمل', 'حبلى'],
      'طفل': ['طفل', 'أطفال', 'صغير', 'ولد', 'صبي'],
      'امرأة': ['امرأة', 'المرأة', 'نساء', 'زوجة', 'بنت', 'أنثى'],
      'رجل': ['رجل', 'الرجل', 'ذكر', 'زوج'],

      // مواضيع
      'ميت': ['ميت', 'موت', 'الموت', 'وفاة', 'متوفى', 'جنازة'],
      'قبر': ['قبر', 'القبر', 'قبور', 'مقبرة', 'دفن'],
      'نية': ['نية', 'النية', 'ينوي', 'نوى', 'القصد'],
      'دعاء': ['دعاء', 'الدعاء', 'يدعو', 'ادعية', 'أدعية'],
      'ذكر': ['ذكر', 'أذكار', 'الذكر', 'تسبيح', 'استغفار'],
      'قرآن': ['قرآن', 'القرآن', 'تلاوة', 'قراءة القرآن'],
      'مسجد': ['مسجد', 'المسجد', 'جامع', 'مصلى'],
      'ربا': ['ربا', 'الربا', 'فائدة', 'فوائد بنكية'],
      'طلاق': ['طلاق', 'الطلاق', 'يطلق', 'طلقها', 'مطلقة'],
      'زواج': ['زواج', 'الزواج', 'نكاح', 'يتزوج', 'خطبة'],
      'حجاب': ['حجاب', 'الحجاب', 'نقاب', 'غطاء', 'ستر'],
      'تشميت': ['تشميت', 'يشمت', 'يرحمك الله', 'شمّت'],
    };

    String result = text;
    final words = text.split(RegExp(r'\s+'));

    for (final word in words) {
      final normalized = word
          .replaceAll('أ', 'ا').replaceAll('إ', 'ا')
          .replaceAll('آ', 'ا').replaceAll('ة', 'ه')
          .replaceAll('ى', 'ي');

      for (final entry in synonymGroups.entries) {
        final normalizedSyns = entry.value.map((s) => s
            .replaceAll('أ', 'ا').replaceAll('إ', 'ا')
            .replaceAll('آ', 'ا').replaceAll('ة', 'ه')
            .replaceAll('ى', 'ي')).toList();

        if (normalizedSyns.contains(normalized)) {
          result = '$result ${entry.key}';
          break;
        }
      }
    }

    return result.trim();
  }
}